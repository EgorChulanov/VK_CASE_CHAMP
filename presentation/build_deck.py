def grid(*cells, style='three'):
    return f'<div class="grid {style}">' + ''.join(cells) + '</div>'


def col(icon, name, body):
    return '<article><h2 class="sectiontitle">' + image(f'icon-{icon}.svg') + name + '</h2>' + body + '</article>'


def item(title, body):
    return f'<div class="entry"><h3>{title}</h3><p>{body}</p></div>'


def box(title, body, style='tint'):
    return f'<aside class="{style}"><h3>{title}</h3><p>{body}</p></aside>'


def stat(number, description, small=False):
    return f'<div class="metric{" small" if small else ""}">{number}</div><div class="sub">{description}</div>'


def bar(label, value, caption, maxval=100, color=BLUE):
    return f'<div class="bar"><div class="barline"><span>{label}</span><b>{caption}</b></div><div class="rail"><i style="width:{value/maxval*100:.3f}%;background:{color}"></i></div></div>'


def tree(root, nodes):
    return '<div class="branch"><b class="rootnode">'+root+'</b><div class="limbs">'+''.join(f'<div class="bnode"><b>{name}</b>{text}</div>' for name,text in nodes)+'</div></div>'


def strip(title, text):
    return f'<div class="strip"><strong>{title}</strong><span>{text}</span></div>'


def route(nodes):
    return '<div class="route">'+''.join(f'<article><h3>{title}</h3><p class="task">{task}</p><p>{tool}</p><small>{measure}</small></article>' for title,task,tool,measure in nodes)+'</div>'


def cash():
    amounts=[-model['investment_rub']]+[r['cumulative_cash'] for r in model['scenarios'][1]['months']]
    x=lambda i: 44+13*i
    y=lambda amount: 53-amount/160000
    lines=''.join(f'<path d="M41 {y(v)}h318" stroke="#d6e2ee"/><text x="0" y="{y(v)+4}">{v//1000000:+}</text>' for v in [-4000000,0,4000000])
    pts=' '.join(f'{x(i)},{y(v):.2f}' for i,v in enumerate(amounts))
    return f'<svg class="cash" viewBox="0 0 380 128">{lines}<polyline points="{pts}" fill="none" stroke="#0077ff" stroke-width="4"/><circle cx="{x(17)}" cy="{y(amounts[17])}" r="5" fill="#007e65"/><text x="225" y="83">17 мес.</text><text x="43" y="117">Старт</text><text x="178" y="117">12 мес.</text><text x="320" y="117">24 мес.</text></svg>'


def flow(nodes):
    return '<div class="flowline">'+''.join(f'<div><strong>{t}</strong>{d}</div>' for t,d in nodes)+'</div>'


