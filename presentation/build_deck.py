def image(name, cls='', alt=''):
    return f'<img src="assets/{name}" class="{cls}" alt="{alt}">'


def slide(tab, eyebrow, title, content):
    n = len(pages) + 1
    links = ''.join(f'<a href="#p{page}" class="{"on" if key == tab else ""}">{key}</a>' for key, page in nav)
