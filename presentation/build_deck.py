def short_journey():
    bands = [
        ("Этап", 0),
        ("Продавец", 2),
        ("Покупатель", 3),
        ("Вопрос покупателя", 4),
        ("Помощь продукта", 5),
        ("Что измерим", 6),
    ]
    rows = []
    for label, key in bands:
        cells = "".join(f"<div>{escape(s[key])}</div>" for s in stages)
        rows.append(
            f'<div class="journeyrow j{key}"><strong>{label}</strong>{cells}</div>'
        )
    return '<div class="journeymap">' + "".join(rows) + "</div>"


