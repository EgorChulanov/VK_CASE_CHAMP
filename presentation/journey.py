def render_page():
    sections = []
    for i, (name, point, *_) in enumerate(stages):
        cards = []
        for _, role, task, touch, barrier, response, measure in (
            x for x in details if x[0] == i
        ):
            kind = "seller" if role == "Продавец" else "buyer"
            rows = "".join(
                f"<dt>{h(label)}</dt><dd>{h(value)}</dd>"
                for label, value in [
                    ("Точка контакта", touch),
                    ("Что может помешать", barrier),
                    ("Как помогает продукт", response),
                    ("Что измерим", measure),
                ]
            )
            cards.append(
                f'<article data-role="{kind}"><span>{h(role)}</span><h3>{h(task)}</h3><dl>{rows}</dl></article>'
            )
        sections.append(
            f'<section id="stage-{i + 1}"><div class="stage"><small>Этап {i + 1}</small><h2>{h(name)}</h2><p>{h(point)}</p></div><div class="cards">{"".join(cards)}</div></section>'
        )
    nav = "".join(
        f'<a href="#stage-{i + 1}">{h(s[0])}</a>' for i, s in enumerate(stages)
    )
    template = (Path(__file__).with_name("journey-template.html")).read_text()
    return template.replace("{{stage_links}}", nav).replace(
        "{{stages}}", "".join(sections)
    )


if __name__ == "__main__":
    (Path(__file__).resolve().parents[1] / "docs/jury/journey.html").write_text(
        render_page()
    )
