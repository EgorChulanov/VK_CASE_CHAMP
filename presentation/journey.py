def data_uri(path, media):
    value = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{media};base64,{value}"


def render_page():
    template = (BASE / "journey-template.html").read_text()
    payload = {"phases": [s[0] for s in stages], "steps": [dict(asdict(s), reason=reason) for s, reason in zip(steps, score_reasons, strict=True)]}
    template = template.replace("{{data}}", json.dumps(payload, ensure_ascii=False).replace("<", "\\u003c"))
    for weight in ["Regular", "Medium", "DemiBold"]:
        template = template.replace("{{font_" + weight + "}}", data_uri(BASE / "fonts" / f"VKSansText-{weight}.woff2", "font/woff2"))
    for key, path in [
        ("catalog", BASE.parent / "docs/images/overview.webp"),
        ("product", BASE / "assets/phone-shop.webp"),
        ("clip", BASE / "assets/phone-clip.webp"),
        ("order", BASE / "assets/phone-order.webp"),
        ("publication", BASE.parent / "docs/images/publication.webp"),
    ]:
        template = template.replace("{{" + key + "}}", data_uri(path, "image/webp"))
    return template


if __name__ == "__main__":
    (BASE.parent / "docs/jury/journey.html").write_text(render_page())
